def append_staff_privacy():
    from .models import LegalPage

    page = LegalPage.objects.filter(slug="confidentialite").first()
    if page is None:
        return
    changed = False
    for lang, text in STAFF_ACCESS_TEXT.items():
        field = f"body_{lang}"
        body = getattr(page, field) or ""
        if STAFF_ACCESS_MARKER not in body:
            setattr(page, field, body + text)
            changed = True
    if changed:
        page.save()
